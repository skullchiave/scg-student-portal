-- =====================================================================
-- 回に「教科書の順番」を持たせる（sort_key）                     2026-09-12
--
-- ■ なぜ要るか（きあ指示）
--   「つなぐにほんごのⅠ（1〜15課）とⅡ（16〜30課）を教科書の単元単位でわけましょう。
--     まとめテストに関しては
--       1-① 1-② 2-① 2-② 2-③ 3-① 3-② 3-③ まとめ1-3 4-① …
--     みたいにしてください。」
--   ＝**毎日のチェックテストとまとめテストを、教科書の進む順に1本に並べたい。**
--
--   いまの一覧は created_at の新しい順でしか並べられない。
--   lesson（"1-①" や "1-3"）は**画面に出す文字**なので、これで並べると
--   1, 10, 11, 12, 13, 2, 3 … と文字の順になってしまい、課の順にならない。
--   → **並べるための値**を別に持つ。表示用と並び用を1つの列に兼ねさせない。
--
-- ■ 形
--   sort_key text … 文字として並べれば課の順になるよう、0詰めで作る
--     毎日 1課の1枚目   → '01-1'
--     毎日 1課の2枚目   → '01-2'
--     まとめ 1〜3課     → '03-9'   ← 3-③（'03-3'）の**あと**に来るよう 9 を使う
--     問題集（全体）    → '99-0'   ← いちばん最後
--   手で作った回・検査用は null のまま＝並びの最後（新しい順で従来どおり）。
--
-- ■ 広げすぎない
--   列を1本足して索引を張るだけ。既存の列・制約・RLS には触らない。
-- =====================================================================

begin;

alter table public.quiz_sets add column if not exists sort_key text;

-- 教材ごとに、この順で並べる
create index if not exists quiz_sets_book_sort
  on public.quiz_sets (source_book, sort_key);

commit;

