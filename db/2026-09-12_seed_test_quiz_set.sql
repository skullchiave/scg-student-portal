--   という2つが同時に起きていた。→ **名前で分かるようにして、触られない約束を作る。**
--
-- ■ 作り
--   source_book  = 'テスト用'            … 先生の画面の「教材で絞る」に別枠で出る
--   source_file  = 'テスト用/動作確認.xlsx'
--   source_sheet = '動作確認'            … (source_file, source_sheet) の一意索引に乗る＝二重に増えない
--   is_open      = true                  … **常に公開**。ここが検査の前提
--   id           = 7e57c0de-…-0001       … 固定。検査から名指しできるように（7e57c0de = testcode）
--
-- ■ 中身は全部つくりもの
--   実在の教材から1問も持ってきていない。**このリポは public** なので、
--   ここに本物の設問を足さないこと（著作権の見解は「公開は学内に限られる」が前提）。
--   正解は 1,2,1,2,… と交互。**全問「1番目」で出すと ちょうど 5/10** になる
--   ＝採点が壊れたらすぐ分かる形にしてある（tests/test_security.py の test_04 がこれを見る）。
--
-- ■ 何度流しても増えない
--   すでに同じ id があれば作らない。中身も id で固定しているので作り直しも安全。
-- =====================================================================

