/* scg-student-portal ルビ表示（2026-09-10）
 * ライブラリ依存ゼロ。
 *
 * ■ 何をするか
 *   教材の設問文には ${昨日}(きのう) という書き方でルビが入っている。
 *   これを <ruby>昨日<rt>きのう</rt></ruby> に直して、漢字の上によみがなを出す。
 *   （教材331本を調べたところ、ルビの書き方はこの1種類だけだった。
 *     ルビあり版とルビなし版が両方ある教材は、きあ判断で**ルビあり版を採用**）
 *
 * ■ 🔴 安全のための順番が命
 *   **先に全部エスケープして、そのあとルビだけタグに戻す。**
 *   ・設問文は先生が Excel に手で書くもので、< や & が混ざりうる
 *   ・エスケープせずに innerHTML へ入れると、書いたとおりのタグが動いてしまう
 *   ・逆に「ルビを変換してからエスケープ」だと、作ったタグまで文字に戻る
 *   エスケープしても ${ } ( ) は変化しないので、この順番で両立する。
 *
 * ■ 使うところ
 *   出題画面の設問文・選択肢、結果画面の設問文と正解。
 *   ★textContent で描いている場所を innerHTML に変えるときは、**必ずこの関数を通す**。
 *     素の文字列を innerHTML に入れる書き方をこのリポに増やさないこと。
 */

/* HTML として特別な意味を持つ文字を、ただの文字にする */
function escHtml(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/* ${漢字}(よみ) → <ruby>漢字<rt>よみ</rt></ruby>
 * ルビが入っていなければ、ただのエスケープ済み文字列が返る（安全側に倒れる）。 */
function rubyHtml(s) {
  return escHtml(s).replace(
    /\$\{([^}]*)\}\(([^)]*)\)/g,
    "<ruby>$1<rt>$2</rt></ruby>"
  );
}

/* ルビを消して、ただの文字列にする（読み上げ・書き出し・検索用）。
 * 画面には出さないが、いずれ「ルビを消す」切り替えを付けるときの土台になる。 */
function rubyStrip(s) {
  return String(s == null ? "" : s).replace(/\$\{([^}]*)\}\(([^)]*)\)/g, "$1");
}

/* 要素へ安全に流し込む。呼び出し側が innerHTML を直接書かなくて済むように。 */
function setRuby(el, s) {
  if (el) el.innerHTML = rubyHtml(s);
}
